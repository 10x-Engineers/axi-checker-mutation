// UCAgent (UnityChip) checker bound to the lab bench. axi_ram_checker.sv is UCAgent's own
// output, unmodified. It is white-box: besides the AXI port it reads axi_ram's internal
// registers and memory, so this set only works with the axi_ram DUT (tb_top.u_dut).
// Mechanical adaptations, all here: observed bus -> s_axi_* ports; 16-bit addresses (the
// DUT's ADDR_WIDTH); internal inputs from tb_top.u_dut; the formal symbolic index fv_idx,
// which formal treats as "any word", tied to 0 in simulation.
module axi_checker_set #(
  parameter int ID_W = 8, parameter int ADDR_W = 32, parameter int DATA_W = 32, parameter int USER_W = 1
) (
  input logic aclk,
  input logic aresetn,
  input logic [ID_W-1:0] awid,
  input logic [ADDR_W-1:0] awaddr,
  input logic [8-1:0] awlen,
  input logic [3-1:0] awsize,
  input logic [2-1:0] awburst,
  input logic awlock,
  input logic [4-1:0] awcache,
  input logic [3-1:0] awprot,
  input logic [4-1:0] awqos,
  input logic [4-1:0] awregion,
  input logic [USER_W-1:0] awuser,
  input logic awvalid,
  input logic awready,
  input logic [DATA_W-1:0] wdata,
  input logic [DATA_W/8-1:0] wstrb,
  input logic wlast,
  input logic [USER_W-1:0] wuser,
  input logic wvalid,
  input logic wready,
  input logic [ID_W-1:0] bid,
  input logic [2-1:0] bresp,
  input logic [USER_W-1:0] buser,
  input logic bvalid,
  input logic bready,
  input logic [ID_W-1:0] arid,
  input logic [ADDR_W-1:0] araddr,
  input logic [8-1:0] arlen,
  input logic [3-1:0] arsize,
  input logic [2-1:0] arburst,
  input logic arlock,
  input logic [4-1:0] arcache,
  input logic [3-1:0] arprot,
  input logic [4-1:0] arqos,
  input logic [4-1:0] arregion,
  input logic [USER_W-1:0] aruser,
  input logic arvalid,
  input logic arready,
  input logic [ID_W-1:0] rid,
  input logic [DATA_W-1:0] rdata,
  input logic [2-1:0] rresp,
  input logic rlast,
  input logic [USER_W-1:0] ruser,
  input logic rvalid,
  input logic rready
);

  axi_ram_checker #(.DATA_WIDTH(DATA_W), .ADDR_WIDTH(16), .ID_WIDTH(ID_W)) u_uc (
    .clk(aclk),
    .rst_n(aresetn),
    .s_axi_awid(awid),
    .s_axi_awaddr(awaddr[15:0]),
    .s_axi_awlen(awlen),
    .s_axi_awsize(awsize),
    .s_axi_awburst(awburst),
    .s_axi_awlock(awlock),
    .s_axi_awcache(awcache),
    .s_axi_awprot(awprot),
    .s_axi_awvalid(awvalid),
    .s_axi_awready(awready),
    .s_axi_wdata(wdata),
    .s_axi_wstrb(wstrb),
    .s_axi_wlast(wlast),
    .s_axi_wvalid(wvalid),
    .s_axi_wready(wready),
    .s_axi_bid(bid),
    .s_axi_bresp(bresp),
    .s_axi_bvalid(bvalid),
    .s_axi_bready(bready),
    .s_axi_arid(arid),
    .s_axi_araddr(araddr[15:0]),
    .s_axi_arlen(arlen),
    .s_axi_arsize(arsize),
    .s_axi_arburst(arburst),
    .s_axi_arlock(arlock),
    .s_axi_arcache(arcache),
    .s_axi_arprot(arprot),
    .s_axi_arvalid(arvalid),
    .s_axi_arready(arready),
    .s_axi_rid(rid),
    .s_axi_rdata(rdata),
    .s_axi_rresp(rresp),
    .s_axi_rlast(rlast),
    .s_axi_rvalid(rvalid),
    .s_axi_rready(rready),
    .read_state_reg(tb_top.u_dut.read_state_reg),
    .write_state_reg(tb_top.u_dut.write_state_reg),
    .mem_wr_en(tb_top.u_dut.mem_wr_en),
    .mem_rd_en(tb_top.u_dut.mem_rd_en),
    .read_id_reg(tb_top.u_dut.read_id_reg),
    .read_addr_reg(tb_top.u_dut.read_addr_reg),
    .read_count_reg(tb_top.u_dut.read_count_reg),
    .read_size_reg(tb_top.u_dut.read_size_reg),
