    .s_axi_rvalid_reg(tb_top.u_dut.s_axi_rvalid_reg),
    .s_axi_rid_pipe_reg(tb_top.u_dut.s_axi_rid_pipe_reg),
    .s_axi_rdata_pipe_reg(tb_top.u_dut.s_axi_rdata_pipe_reg),
    .s_axi_rlast_pipe_reg(tb_top.u_dut.s_axi_rlast_pipe_reg),
    .s_axi_rvalid_pipe_reg(tb_top.u_dut.s_axi_rvalid_pipe_reg),
    .fv_idx('0)
  );

endmodule
