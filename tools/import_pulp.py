#!/usr/bin/env python3
"""Generate checkers/pulp_axi/axi_checker_set.sv from PULP axi's AXI_BUS_DV assertions.

The open-source baseline is the assertion block of `AXI_BUS_DV` in
third_party/pulp-axi/src/axi_intf.sv (Solderpad SHL-0.51). Upstream guards it with
`ifndef VERILATOR`, so it is lifted out here. Three mechanical changes, nothing else:
  - signal names: aw_valid -> awvalid, clk_i -> aclk, ...
  - each assertion gets the label p_L<upstream line number>, so fires trace back to source
  - `else $error(...)` action blocks are dropped, so every failure reports the same way
Property expressions are kept verbatim, defects included.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "pulp-axi" / "src" / "axi_intf.sv"
OUT = ROOT / "checkers" / "pulp_axi" / "axi_checker_set.sv"
PORTS = (ROOT / "checkers" / "none" / "axi_checker_set.sv").read_text()


def main():
    lines = SRC.read_text().split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip().startswith("interface AXI_BUS_DV"))
    off = next(i for i in range(start, len(lines)) if "translate_off" in lines[i])
    on = next(i for i in range(off, len(lines)) if "translate_on" in lines[i])

    props, cur, cur_line = [], [], None
    for i in range(off + 1, on):
        l = lines[i]
        if l.strip().startswith("`") or l.strip().startswith("//"):
            continue
        if "assert property" in l:
            cur, cur_line = [], i + 1
        if cur_line is not None:
            cur.append(l.split("//", 1)[0])
            text = " ".join(cur)
            if text.count("(") == text.count(")") and (";" in l):
                props.append((cur_line, text))
                cur_line = None

    ports = set(re.findall(r"input logic (?:\[[^\]]*\] )?(\w+)", PORTS))
    body, dropped = [], []
    for line_no, text in props:
        text = re.sub(r"\)\s*else\s+\$error\(.*\)\s*;\s*$", ");", text)
        text = re.sub(r"\b([awbr]{1,2})_(\w+)\b", lambda m: m.group(1) + m.group(2), text)
        text = text.replace("clk_i", "aclk")
        text = re.sub(r"\s+", " ", text).strip()
        sigs = set(re.findall(r"\b(?:aw|w|b|ar|r)[a-z]+\b", text)) - {"axi_pkg"}
        missing = sorted(x for x in sigs if x not in ports and not x.startswith("beat"))
        if missing:
            dropped.append((line_no, missing))
            continue
        body.append(f"  // axi_intf.sv:{line_no}\n  p_L{line_no}: {text}")

    header = PORTS.split("module axi_checker_set", 1)[1].split(");", 1)[0]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by tools/import_pulp.py from third_party/pulp-axi/src/axi_intf.sv\n"
        "// (AXI_BUS_DV assertions, Solderpad SHL-0.51, (c) ETH Zurich / University of Bologna).\n"
        "// Only signal names, labels and removed $error action blocks differ from upstream.\n"
        + "".join(f"// Not imported: axi_intf.sv:{n} uses {', '.join(m)}, which an AXI4 interface does not have.\n"
                  for n, m in dropped)
        + "module axi_checker_set" + header + ");\n\n" + "\n\n".join(body) + "\n\nendmodule\n")
    print(f"{len(body)} of {len(props)} assertions -> {OUT.relative_to(ROOT)}; dropped {dropped}")


if __name__ == "__main__":
    main()
